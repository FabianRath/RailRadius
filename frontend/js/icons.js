/** Inline SVG markup; it draws in `currentColor`, so the surrounding CSS colours it. */
export function icon(name) {
    return '<svg class="icon" viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="2"'
        + ` stroke-linecap="round" stroke-linejoin="round" aria-hidden="true">${ICONS[name]}</svg>`;
}

/** Fills the `<span data-icon="…">` placeholders in the static markup. */
export function renderStaticIcons() {
    document.querySelectorAll('[data-icon]').forEach(slot => {
        slot.innerHTML = icon(slot.dataset.icon);
    });
}
